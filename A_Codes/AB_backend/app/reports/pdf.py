"""Render a stored model risk report as a PDF (REQ-REG-10A).

Rendering only: every figure is taken from the stored copy, nothing is recomputed here. A report
reopened in two years must print what it said when it was generated, so this module must never reach
for a service or the database.

`reportlab` was chosen because it installs as a pure-Python wheel and renders on Python 3.14 under
Windows, which WeasyPrint does not without native GTK (D12, 2026-10-06).
"""
from datetime import date, datetime

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import KeepTogether, PageBreak, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

import io

HEADER_FILL = colors.HexColor("#DDE1EA")
MUTED = colors.HexColor("#5A6472")
BAD = colors.HexColor("#A3302A")


def _styles():
    s = getSampleStyleSheet()
    s.add(ParagraphStyle("Lede", parent=s["Normal"], textColor=MUTED, fontSize=9, spaceAfter=10))
    s.add(ParagraphStyle("Sec", parent=s["Heading2"], fontSize=12, spaceBefore=14, spaceAfter=6))
    s.add(ParagraphStyle("Note", parent=s["Normal"], textColor=MUTED, fontSize=8, spaceBefore=4))
    return s


def _table(rows: list[list], widths: list[float] | None = None) -> Table:
    t = Table(rows, colWidths=widths, hAlign="LEFT")
    t.setStyle(TableStyle([
        ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#C3C9D4")),
        ("BACKGROUND", (0, 0), (-1, 0), HEADER_FILL),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 8),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("TOPPADDING", (0, 0), (-1, -1), 3),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
    ]))
    return t


def _distribution(title: str, rows: list[dict], styles) -> list:
    # Prefer the stored label: score bands carry one, and a board report cannot say "below_warn".
    body = [["", "Models"]] + [[str(r.get("label") or r["key"]), str(r["count"])] for r in rows]
    body[0][0] = title
    return [_table(body, [70 * mm, 25 * mm]), Spacer(1, 6)]


def _count_or_none(items: list, singular: str, plural: str) -> str:
    n = len(items)
    return f"{n} {singular if n == 1 else plural}"


def render(report: dict, sections: dict) -> bytes:
    """`report` is the stored row's header fields; `sections` is the stored content."""
    styles = _styles()
    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf, pagesize=A4, title=f"Model Risk Report {report['business_date']}",
        author=report.get("generated_by") or "", subject=report.get("framework_label") or "",
        leftMargin=18 * mm, rightMargin=18 * mm, topMargin=16 * mm, bottomMargin=16 * mm)
    flow: list = []

    # Header (REQ-REG-10A)
    flow.append(Paragraph("Model Risk Report", styles["Title"]))
    generated = report.get("generated_at")
    if isinstance(generated, (datetime, date)):
        generated = generated.isoformat(sep=" ", timespec="seconds") if isinstance(generated, datetime) \
            else generated.isoformat()
    flow.append(Paragraph(
        f"{report.get('framework_label', '')}<br/>"
        f"Business date {report['business_date']} &middot; report {report['report_id']}<br/>"
        f"Generated by {report.get('generated_by') or 'system'} at {generated}<br/>"
        # S12, extended to the PDF by D14: a past-tense fact about this report, on the copy that
        # leaves the system, not only on the screen (CR-55).
        f"Figures reconciled with the Command Center at generation, {generated}.", styles["Lede"]))
    if report.get("seeded_label"):
        # D14: the seeded example says what it is and which date its figures belong to (TR-48).
        flow.append(Paragraph(f"<b>{report['seeded_label']}</b>", styles["Lede"]))

    inv = sections["inventory"]
    flow.append(Paragraph(f"Inventory — {inv['total']} models", styles["Sec"]))
    flow += _distribution("Risk tier", inv["by_tier"], styles)
    flow += _distribution("Stage (as displayed)", inv["by_stage"], styles)
    flow.append(Paragraph(
        "Stage is the column the Command Center displays: a model in Monitoring inside its "
        "revalidation lead time is shown in Revalidation.", styles["Note"]))

    val = sections["validation"]
    flow.append(Paragraph("Validation", styles["Sec"]))
    flow += _distribution("Revalidation status", val["by_status"], styles)
    if val["overdue"]:
        rows = [["Model", "Name", "Tier", "Owner", "Days overdue"]] + [
            [m["model_id"], m["model_name"][:38], m["tier"], m["owner_id"] or "",
             str(m.get("days_overdue") or "")] for m in val["overdue"]]
        flow.append(Paragraph(f"Overdue ({len(val['overdue'])}), highest tier first", styles["Normal"]))
        flow.append(Spacer(1, 4))
        flow.append(_table(rows, [22 * mm, 60 * mm, 18 * mm, 20 * mm, 24 * mm]))
    else:
        flow.append(Paragraph("No overdue revalidations.", styles["Normal"]))

    fnd = sections["findings"]
    flow.append(Paragraph("Findings", styles["Sec"]))
    flow += _distribution("Open by severity", fnd["open_by_severity"], styles)
    flow += _distribution("Overdue by severity", fnd["overdue_by_severity"], styles)
    if fnd["critical_overdue"]:
        rows = [["Finding", "Model", "Title", "Days overdue"]] + [
            [f["finding_id"], f["model_id"], f["title"][:46], str(f["days_overdue"])]
            for f in fnd["critical_overdue"]]
        t = _table(rows, [24 * mm, 22 * mm, 74 * mm, 24 * mm])
        t.setStyle(TableStyle([("TEXTCOLOR", (3, 1), (3, -1), BAD)]))
        flow.append(KeepTogether([Paragraph("Critical and overdue", styles["Normal"]), Spacer(1, 4), t]))

    flow.append(PageBreak())

    apr = sections["approvals"]
    flow.append(Paragraph("Approvals", styles["Sec"]))
    if apr["conditional_open"]:
        rows = [["Model", "Name", "Open conditions", "Latest decision"]] + [
            [a["model_id"], a["model_name"][:34], str(a["open_conditions"]), a.get("latest_decision") or ""]
            for a in apr["conditional_open"]]
        flow.append(_table(rows, [22 * mm, 56 * mm, 28 * mm, 34 * mm]))
    else:
        flow.append(Paragraph("No approvals with open conditions.", styles["Normal"]))

    sc = sections["score"]
    flow.append(Paragraph(f"Governance score — portfolio {sc['portfolio_score']}", styles["Sec"]))
    flow += _distribution("Score band", sc["by_band"], styles)
    if sc["lowest"]:
        rows = [["Model", "Name", "Score", "Weakest component"]] + [
            [m["model_id"], m["model_name"][:34], str(m["score"]), m.get("weakest_component") or ""]
            for m in sc["lowest"]]
        flow.append(Paragraph("Lowest scoring", styles["Normal"]))
        flow.append(Spacer(1, 4))
        flow.append(_table(rows, [22 * mm, 56 * mm, 20 * mm, 42 * mm]))

    docs = sections["documentation"]
    flow.append(Paragraph(f"Documentation — {docs['completeness_pct']}% complete", styles["Sec"]))
    missing = docs["models_missing_documents"]
    if missing:
        rows = [["Model", "Phase", "Missing"]] + [
            [m["model_id"], m["lifecycle_phase"], ", ".join(m["missing"])[:60]] for m in missing]
        flow.append(_table(rows, [22 * mm, 30 * mm, 88 * mm]))
    else:
        flow.append(Paragraph("No required documents missing.", styles["Normal"]))

    ch = sections["changes_since"]
    flow.append(Paragraph("Changes since the previous report", styles["Sec"]))
    if ch["previous_report_id"] is None:
        flow.append(Paragraph("This is the first report, so there is nothing to compare against.",
                              styles["Normal"]))
    else:
        rows = [["Change", "Count"],
                ["Models added", str(len(ch["models_added"]))],
                ["Models retired", str(len(ch["models_retired"]))],
                ["Phase changes", str(len(ch["phase_changes"]))],
                ["Findings opened", str(len(ch["findings_opened"]))],
                ["Findings closed", str(len(ch["findings_closed"]))],
                # S13: decisions recorded since the previous report live in this section. A pre-S13
                # stored copy is carried to this shape by `report_service.read_sections` (TR-61).
                ["Approval decisions recorded", str(len(ch["decisions_recorded"]))]]
        flow.append(_table(rows, [70 * mm, 25 * mm]))
        flow.append(Paragraph(f"Compared against {ch['previous_report_id']}.", styles["Note"]))

    doc.build(flow)
    return buf.getvalue()
