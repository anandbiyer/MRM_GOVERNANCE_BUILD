/**
 * Model Risk Report (BRD §55.10, §12A REQ-REG-10A; criteria REG-15, REG-17).
 *
 * The report is always generated for the current business date — there is no date picker, because
 * there is no past-date report. History is the stored copies listed below, and reopening one renders
 * what it said then, from the stored content rather than from today's records.
 */
import { useMutation, useQueryClient } from "@tanstack/react-query";
import { useState } from "react";
import { Link } from "react-router-dom";
import { api, downloadFile } from "../api/client";
import { useModelRiskReport, useModelRiskReports } from "../api/queries";
import { useAuth } from "../auth/AuthContext";
import { EmptyState, ErrorState, Loading, PageHeader } from "../components/States";
import type { ModelRiskReportDetail, ReportCount, ReportSections } from "../api/types";
import { Pill } from "../components/Pills";
import { formatDate, formatDateTime } from "../format";

function Distribution({ title, rows }: { title: string; rows: ReportCount[] }) {
  const total = rows.reduce((n, r) => n + r.count, 0);
  return (
    <div className="tablewrap">
      <table>
        <thead><tr><th>{title}</th><th>Models</th><th>Share</th></tr></thead>
        <tbody>
          {rows.map((r) => (
            <tr key={r.key}>
              <td>{r.label ?? r.key}</td>
              <td className="mono">{r.count}</td>
              <td className="mono">{total ? Math.round((100 * r.count) / total) : 0}%</td>
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}

/** A section's record list. Columns are named by the caller, so an older report still renders. */
function RowList({ rows, columns }: { rows: Record<string, unknown>[]; columns: string[] }) {
  if (rows.length === 0) return <p className="note">None.</p>;
  return (
    <div className="tablewrap scroll">
      <table>
        <thead><tr>{columns.map((c) => <th key={c}>{c.replace(/_/g, " ")}</th>)}</tr></thead>
        <tbody>
          {rows.map((r, i) => (
            <tr key={String(r.model_id ?? r.finding_id ?? r.approval_id ?? i)}>
              {columns.map((c) => (
                <td key={c} className={c.endsWith("_id") || c === "score" ? "mono" : undefined}>
                  {r[c] === null || r[c] === undefined ? "—" : String(r[c])}
                </td>
              ))}
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}

function ChangesSince({ changes }: { changes: ReportSections["changes_since"] }) {
  if (!changes.previous_report_id) {
    return <p className="note">This is the first report, so there is nothing to compare against.</p>;
  }
  const rows: [string, Record<string, unknown>[]][] = [
    ["Models added", changes.models_added],
    ["Models retired", changes.models_retired],
    ["Phase changes", changes.phase_changes],
    ["Findings opened", changes.findings_opened],
    ["Findings closed", changes.findings_closed],
  ];
  return (
    <>
      <p className="note">Compared against {changes.previous_report_id}.</p>
      <div className="tablewrap">
        <table>
          <thead><tr><th>Change</th><th>Count</th><th>Records</th></tr></thead>
          <tbody>
            {rows.map(([label, items]) => (
              <tr key={label}>
                <td>{label}</td>
                <td className="mono">{items.length}</td>
                <td className="mono">
                  {items.length === 0 ? "—" : items
                    .map((r) => String(r.model_id ?? r.finding_id ?? ""))
                    .filter(Boolean).join(", ")}
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    </>
  );
}

function ReportView({ report }: { report: ModelRiskReportDetail }) {
  const s = report.sections;
  return (
    <div className="stack">
      <section className="panel">
        <h3>{report.framework_label}{report.is_seeded && <> <Pill value="Seeded example" /></>}</h3>
        <p className="note">
          Business date {formatDate(report.business_date)} · {report.report_id} · generated by{" "}
          {report.generated_by ?? "system"} at {formatDateTime(report.generated_at)}
          <br />Content hash <span className="mono">{report.content_hash.slice(0, 16)}…</span>
          {/* S12: a past-tense fact about *this* report, inside the report view. The claim it
              replaced was rendered at page level, so it was asserted over whichever report was
              open — false for a historical one, and unverifiable by construction, because the
              Command Center has no as-of control and always renders today. */}
          <br />Figures reconciled with the <Link to="/">Command Center</Link> at generation,{" "}
          {formatDateTime(report.generated_at)}.
          {report.is_seeded && <>
            {" "}This is a <b>seeded example</b>: its figures are the service's own, but its
            comparison baseline was shaped so the next report has changes to show.
          </>}
        </p>
        <button className="btn sm" onClick={() => void downloadFile(
          `/api/reports/model-risk/${report.report_id}/pdf`, `${report.report_id}.pdf`)}>
          Download PDF
        </button>
      </section>

      <section className="panel">
        <h4>Inventory — {s.inventory.total} models</h4>
        <Distribution title="Risk tier" rows={s.inventory.by_tier} />
        <Distribution title="Stage (as displayed)" rows={s.inventory.by_stage} />
        <p className="note">
          Stage is the column the Command Center displays: a model in Monitoring inside its
          revalidation lead time is shown in Revalidation.
        </p>
      </section>

      <section className="panel">
        <h4>Validation</h4>
        <Distribution title="Revalidation status" rows={s.validation.by_status} />
        <h5>Overdue ({s.validation.overdue.length}), highest tier first</h5>
        <RowList rows={s.validation.overdue}
                 columns={["model_id", "model_name", "tier", "owner_id", "days_overdue"]} />
      </section>

      <section className="panel">
        <h4>Findings</h4>
        <Distribution title="Open by severity" rows={s.findings.open_by_severity} />
        <Distribution title="Overdue by severity" rows={s.findings.overdue_by_severity} />
        <h5>Critical and overdue ({s.findings.critical_overdue.length})</h5>
        <RowList rows={s.findings.critical_overdue}
                 columns={["finding_id", "model_id", "title", "days_overdue"]} />
      </section>

      <section className="panel">
        <h4>Approvals</h4>
        <h5>Conditional with open conditions ({s.approvals.conditional_open.length})</h5>
        <RowList rows={s.approvals.conditional_open}
                 columns={["model_id", "model_name", "open_conditions", "latest_decision"]} />
        <h5>Decisions since the previous report ({s.approvals.decisions_since_previous.length})</h5>
        <RowList rows={s.approvals.decisions_since_previous}
                 columns={["approval_id", "model_id", "decision", "decision_type", "decision_date"]} />
      </section>

      <section className="panel">
        <h4>Governance score — portfolio {s.score.portfolio_score ?? "—"}</h4>
        <Distribution title="Score band" rows={s.score.by_band} />
        <h5>Lowest scoring</h5>
        <RowList rows={s.score.lowest}
                 columns={["model_id", "model_name", "score", "weakest_component"]} />
      </section>

      <section className="panel">
        <h4>Documentation — {s.documentation.completeness_pct}% complete</h4>
        <RowList rows={s.documentation.models_missing_documents}
                 columns={["model_id", "model_name", "lifecycle_phase", "missing"]} />
      </section>

      <section className="panel">
        <h4>Changes since the previous report</h4>
        <ChangesSince changes={s.changes_since} />
      </section>
    </div>
  );
}

export function ModelRiskReportPage() {
  const { can } = useAuth();
  const qc = useQueryClient();
  const reports = useModelRiskReports();
  const [selected, setSelected] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);

  // The generated report comes back in the POST response, so it is shown without a second fetch.
  const [fresh, setFresh] = useState<ModelRiskReportDetail | null>(null);
  const generate = useMutation({
    mutationFn: () => api<ModelRiskReportDetail>("/api/reports/model-risk", { method: "POST" }),
    onSuccess: (r) => {
      setFresh(r);
      setSelected(r.report_id);
      setError(null);
      qc.invalidateQueries({ queryKey: ["model-risk-reports"] });
    },
    onError: (e: Error) => setError(e.message),
  });

  const stored = useModelRiskReport(selected && selected !== fresh?.report_id ? selected : undefined);
  const showing = selected === fresh?.report_id ? fresh : stored.data ?? null;

  if (reports.isLoading) return <Loading />;
  if (reports.isError) return <ErrorState error={reports.error} />;

  return (
    <div className="stack">
      <PageHeader
        eyebrow="Control"
        title="Model Risk Report"
        lede="A point-in-time report for senior management and the MRC, built from the governance records. Every figure equals the Command Center on the same business date."
      />

      <section className="panel">
        {can("report:generate") ? (
          <>
            <button className="btn primary" disabled={generate.isPending}
                    onClick={() => generate.mutate()}>
              {generate.isPending ? "Generating…" : "Generate report"}
            </button>
            <p className="note" style={{ marginTop: 8 }}>
              The report is always for the current business date. Earlier reports are the stored
              copies below — reopening one shows what it said then.
            </p>
          </>
        ) : (
          <p className="note">
            You can read and download reports. Generating one needs the report:generate permission
            (Admin, MRC Member or Validator).
          </p>
        )}
        {error && <div className="errline" style={{ marginTop: 8 }}>{error}</div>}
      </section>

      <section className="panel">
        <h3>Earlier reports</h3>
        {reports.data && reports.data.length === 0 ? (
          <EmptyState title="No reports yet">
            {can("report:generate")
              ? "Generate one above."
              : "Ask an Admin, MRC Member or Validator to generate one."}
          </EmptyState>
        ) : (
          <div className="tablewrap scroll">
            <table>
              <thead>
                <tr><th>Report</th><th>Business date</th><th>Generated</th><th>By</th><th></th></tr>
              </thead>
              <tbody>
                {reports.data?.map((r) => (
                  <tr key={r.report_id} className={r.report_id === selected ? "on" : undefined}>
                    <td className="mono">{r.report_id}{r.is_seeded &&
                      <> <Pill value="Seeded example" /></>}</td>
                    <td className="mono">{formatDate(r.business_date)}</td>
                    <td>{formatDateTime(r.generated_at)}</td>
                    <td className="mono">{r.generated_by ?? "system"}</td>
                    <td>
                      <button className="btn sm"
                              onClick={() => { setSelected(r.report_id); setError(null); }}>
                        {r.report_id === selected ? "Showing" : "Open"}
                      </button>{" "}
                      <button className="btn sm" onClick={() => void downloadFile(
                        `/api/reports/model-risk/${r.report_id}/pdf`, `${r.report_id}.pdf`)}>
                        PDF
                      </button>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </section>

      {stored.isLoading && <Loading label="Opening report…" />}
      {stored.isError && <ErrorState error={stored.error} title="Could not open that report" />}
      {showing && <ReportView report={showing} />}
    </div>
  );
}
